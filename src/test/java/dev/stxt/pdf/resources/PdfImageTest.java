/**
 * The PDFs of {@code images/} (reference/components/image.md): the size of each page, already cropped and rotated,
 * and what prevents drawing it. The files of {@code resources/images/test/} are generated by
 * {@code tools/ExamplePdfs.java}; the fonts that break the other rules of PDF/UA, here, with PDFBox: a page that says
 * "Hola" in IBM Plex Sans, broken afterwards.
 */
class PdfImageTest {

    private final ImageLibrary images = new Resources().images();

    @TempDir
    Path dir;

    @Test
    void eachPageHasItsSizeCroppedAndTurned() {
        ImageFile f = images.find("test/pages.pdf");
        assertEquals(ImageFile.Format.PDF, f.format());
        assertTrue(f.isVector());
        assertEquals(0, f.pixels());
        assertEquals(3, f.pages());
        // Page 1, 200 × 100; page 2, cropped to 150 × 50; page 3, 200 × 100 rotated 90°: it shows as 100 × 200.
        assertEquals(200, f.width(1), 1e-9);
        assertEquals(100, f.height(1), 1e-9);
        assertEquals(150, f.width(2), 1e-9);
        assertEquals(50, f.height(2), 1e-9);
        assertEquals(100, f.width(3), 1e-9);
        assertEquals(200, f.height(3), 1e-9);
        // Without Page, the first one.
        assertEquals(200, f.width(), 1e-9);
        assertEquals(100, f.height(), 1e-9);
        for (int page = 1; page <= 3; page++) {
            assertNull(f.problem(page, Check.PDF_IMAGE_FONTS));
            assertNull(f.problem(page, Check.PDF_IMAGE_ANNOTATIONS));
        }
    }

    @Test
    void theOtherFormatsHaveOnePage() {
        ImageFile png = images.find("test/wide.png");
        assertEquals(1, png.pages());
        assertNull(png.problem(1, Check.PDF_IMAGE_FONTS));
        assertEquals(png.width(), png.width(1), 1e-9);
    }

    @Test
    void aFontThatIsNotEmbeddedCannotBeDrawn() {
        ImageFile f = images.find("test/standard-font.pdf");
        String problem = f.problem(1, Check.PDF_IMAGE_FONTS);
        assertTrue(problem.contains("Helvetica not embedded"), problem);
        assertNull(f.problem(1, Check.PDF_IMAGE_ANNOTATIONS));
    }

    /** Without {@code ToUnicode}, a Type 0 font does not say which character each glyph is. */
    @Test
    void aFontWithoutUnicodeCannotBeDrawn() {
        String problem = images.find("test/no-unicode.pdf").problem(1, Check.PDF_IMAGE_FONTS);
        assertTrue(problem.contains("without ToUnicode"), problem);
    }

    @Test
    void aVisibleAnnotationCannotBeDrawn() {
        ImageFile f = images.find("test/form-field.pdf");
        String problem = f.problem(1, Check.PDF_IMAGE_ANNOTATIONS);
        assertTrue(problem.contains("Widget"), problem);
        assertNull(f.problem(1, Check.CONTRAST));
    }

    @Test
    void anEncryptedPdfIsAnError() {
        ImageFormatException e = assertThrows(ImageFormatException.class, () -> images.find("test/encrypted.pdf"));
        assertTrue(e.getMessage().contains("test/encrypted.pdf is encrypted"), e.getMessage());
    }

    @Test
    void aDamagedPdfIsAnError() throws IOException {
        Path file = dir.resolve("broken.pdf");
        Files.writeString(file, "%PDF-1.7\nnada más\n", StandardCharsets.ISO_8859_1);
        ImageFormatException e = assertThrows(ImageFormatException.class,
                () -> ImageFile.read(file, "broken.pdf", new Resources()));
        assertTrue(e.getMessage().contains("broken.pdf, which looks like a PDF but is damaged"), e.getMessage());
    }

    /** A page in a Type 0 font and another in a TrueType one, both well made: the edits below break them. */
    @Test
    void wellMadeFontsCanBeDrawn() throws IOException {
        assertNull(fonts(true, (doc, page, font) -> { }));
        assertNull(fonts(false, (doc, page, font) -> { }));
    }

    @Test
    void aType2CidFontNeedsItsCidToGidMap() throws IOException {
        String problem = fonts(true, (doc, page, font) -> descendant(font).removeItem(COSName.CID_TO_GID_MAP));
        assertTrue(problem.contains("without CIDToGIDMap"), problem);
    }

    /** A TrueType font that is not symbolic is in WinAnsiEncoding or MacRomanEncoding, with names of the Adobe list. */
    @Test
    void aTrueTypeFontThatIsNotSymbolicNeedsAStandardEncoding() throws IOException {
        String problem = fonts(false, (doc, page, font) -> font.removeItem(COSName.ENCODING));
        assertTrue(problem.contains("without the encoding WinAnsiEncoding or MacRomanEncoding"), problem);

        problem = fonts(false, (doc, page, font) -> {
            COSDictionary encoding = new COSDictionary();
            encoding.setItem(COSName.BASE_ENCODING, COSName.WIN_ANSI_ENCODING);
            COSArray differences = new COSArray();
            differences.add(COSInteger.get(72));
            differences.add(COSName.getPDFName("H"));
            encoding.setItem(COSName.DIFFERENCES, differences);
            font.setItem(COSName.ENCODING, encoding);
        });
        assertNull(problem, "H is in the Adobe Glyph List");

        problem = fonts(false, (doc, page, font) -> {
            COSDictionary encoding = new COSDictionary();
            encoding.setItem(COSName.BASE_ENCODING, COSName.MAC_ROMAN_ENCODING);
            COSArray differences = new COSArray();
            differences.add(COSInteger.get(72));
            differences.add(COSName.getPDFName("notaglyph"));
            encoding.setItem(COSName.DIFFERENCES, differences);
            font.setItem(COSName.ENCODING, encoding);
        });
        assertTrue(problem.contains("glyph names outside the Adobe Glyph List"), problem);
    }

    /** A symbolic TrueType font, with its ToUnicode so that it says which character each glyph is, has no Encoding. */
    @Test
    void aSymbolicTrueTypeFontHasNoEncoding() throws IOException {
        String problem = fonts(false, (doc, page, font) -> {
            font.getCOSDictionary(COSName.FONT_DESC).setInt(COSName.FLAGS, 4);
            font.setItem(COSName.TO_UNICODE, toUnicode(doc, "<20> <7E> <0020>"));
        });
        assertTrue(problem.contains("symbolic TrueType font IBMPlexSans with an Encoding"), problem);

        // Without it, the cmap table of IBM Plex Sans has several encodings and not the Microsoft Symbol one.
        problem = fonts(false, (doc, page, font) -> {
            font.getCOSDictionary(COSName.FONT_DESC).setInt(COSName.FLAGS, 4);
            font.setItem(COSName.TO_UNICODE, toUnicode(doc, "<20> <7E> <0020>"));
            font.removeItem(COSName.ENCODING);
        });
        assertTrue(problem.contains("without the Microsoft Symbol one"), problem);
    }

    @Test
    void aGlyphThatTheFontDoesNotHaveCannotBeDrawn() throws IOException {
        String problem = fonts(true, (doc, page, font) -> content(doc, page, "BT /F1 14 Tf 10 70 Td <0000> Tj ET"));
        assertTrue(problem.contains("the character code 0, which the font does not have"), problem);
    }

    /** With ToUnicode, but without the codes that the page draws. */
    @Test
    void aCodeThatTheToUnicodeDoesNotHaveCannotBeDrawn() throws IOException {
        String problem = fonts(true, (doc, page, font) ->
                font.setItem(COSName.TO_UNICODE, toUnicode(doc, "<FFFE> <FFFF> <0041>")));
        assertTrue(problem.contains("without saying which character the code"), problem);
    }

    /** The widths of the font dictionary are not those of its font program; invisible text does not count. */
    @Test
    void aWidthThatIsNotTheOneOfTheFontCannotBeDrawn() throws IOException {
        Edit wrongWidths = (doc, page, font) -> {
            COSArray widths = new COSArray();
            widths.add(COSInteger.get(0));
            widths.add(COSInteger.get(65535));
            widths.add(COSInteger.get(900));
            descendant(font).setItem(COSName.W, widths);
        };
        String problem = fonts(true, wrongWidths);
        assertTrue(problem.contains("with a width for the character code"), problem);

        assertNull(fonts(true, (doc, page, font) -> {
            wrongWidths.apply(doc, page, font);
            COSArray contents = new COSArray();
            contents.add(stream(doc, "3 Tr\n"));
            contents.add(page.getCOSObject().getDictionaryObject(COSName.CONTENTS));
            page.getCOSObject().setItem(COSName.CONTENTS, contents);
        }));
    }

    /** A tiling pattern is drawn only when something is filled with it: its glyphs are checked as well. */
    @Test
    void theGlyphsOfATilingPatternAreChecked() throws IOException {
        String problem = fonts(true, (doc, page, font) -> {
            COSStream pattern = stream(doc, "BT /F1 8 Tf 0 2 Td <0000> Tj ET");
            pattern.setItem(COSName.TYPE, COSName.PATTERN);
            pattern.setInt(COSName.PATTERN_TYPE, 1);
            pattern.setInt(COSName.PAINT_TYPE, 1);
            pattern.setInt(COSName.TILING_TYPE, 1);
            pattern.setItem(COSName.BBOX, new PDRectangle(0, 0, 20, 10).getCOSArray());
            pattern.setInt(COSName.X_STEP, 20);
            pattern.setInt(COSName.Y_STEP, 10);
            pattern.setItem(COSName.RESOURCES, page.getResources().getCOSObject());
            COSDictionary patterns = new COSDictionary();
            patterns.setItem(COSName.getPDFName("P1"), pattern);
            page.getResources().getCOSObject().setItem(COSName.PATTERN, patterns);
            content(doc, page, "/Pattern cs /P1 scn 0 0 200 20 re f");
        });
        assertTrue(problem.contains("the character code 0, which the font does not have"), problem);
    }

    private static final File PLEX = Path.of("resources", "fonts", "IBM Plex Sans", "IBMPlexSans-Regular.ttf").toFile();

    /** A change to the PDF: {@code font} is the dictionary of its only font, which the page calls {@code F1}. */
    private interface Edit {
        void apply(PDDocument doc, PDPage page, COSDictionary font) throws IOException;
    }

    /** What the inspector says about the fonts of the page that says "Hola", once {@code edit} has changed it. */
    private String fonts(boolean type0, Edit edit) throws IOException {
        ByteArrayOutputStream bytes = new ByteArrayOutputStream();
        try (PDDocument doc = new PDDocument()) {
            PDPage page = new PDPage(new PDRectangle(200, 100));
            doc.addPage(page);
            PDFont font = type0 ? PDType0Font.load(doc, PLEX)
                    : PDTrueTypeFont.load(doc, PLEX, WinAnsiEncoding.INSTANCE);
            page.setResources(new PDResources());
            page.getResources().put(COSName.getPDFName("F1"), font);
            try (PDPageContentStream content = new PDPageContentStream(doc, page)) {
                content.beginText();
                content.setFont(font, 14);
                content.newLineAtOffset(10, 40);
                content.showText("Hola");
                content.endText();
            }
            // The Type 0 font is subset when the document is saved.
            doc.save(bytes);
        }
        Path file = dir.resolve("fonts.pdf");
        try (PDDocument doc = Loader.loadPDF(bytes.toByteArray())) {
            PDPage page = doc.getPage(0);
            edit.apply(doc, page, page.getResources().getFont(COSName.getPDFName("F1")).getCOSObject());
            doc.save(file.toFile());
        }
        return ImageFile.read(file, "fonts.pdf", new Resources()).problem(1, Check.PDF_IMAGE_FONTS);
    }

    private static COSDictionary descendant(COSDictionary type0) {
        return (COSDictionary) type0.getCOSArray(COSName.DESCENDANT_FONTS).getObject(0);
    }

    /** Adds a content stream to the end of the page. */
    private static void content(PDDocument doc, PDPage page, String operators) throws IOException {
        COSArray contents = new COSArray();
        COSBase current = page.getCOSObject().getDictionaryObject(COSName.CONTENTS);
        if (current instanceof COSArray array) {
            contents.addAll(array);
        } else {
            contents.add(current);
        }
        contents.add(stream(doc, operators));
        page.getCOSObject().setItem(COSName.CONTENTS, contents);
    }

    /** A ToUnicode CMap with one range of one byte or two ({@code <from> <to> <first character>}). */
    private static COSStream toUnicode(PDDocument doc, String range) throws IOException {
        String bytes = range.indexOf('>') == 3 ? "<00> <FF>" : "<0000> <FFFF>";
        return stream(doc, "/CIDInit /ProcSet findresource begin 12 dict begin begincmap\n"
                + "/CMapName /Test def /CMapType 2 def\n1 begincodespacerange " + bytes + " endcodespacerange\n"
                + "1 beginbfrange " + range + " endbfrange\n"
                + "endcmap CMapName currentdict /CMap defineresource pop end end\n");
    }

    private static COSStream stream(PDDocument doc, String text) throws IOException {
        COSStream stream = doc.getDocument().createCOSStream();
        try (OutputStream out = stream.createOutputStream()) {
            out.write(text.getBytes(StandardCharsets.ISO_8859_1));
        }
        return stream;
    }
}
