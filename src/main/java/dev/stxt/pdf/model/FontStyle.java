package dev.stxt.pdf.model;

/**
 * Style of a font: {@code Italic} of {@code Typography} (reference/common/typography.md). The
 * constants are named after the document value, in upper case.
 */
public enum FontStyle {
    /** {@code Italic: false}: the regular variant of the font. */
    NORMAL,
    /** {@code Italic: true}: the italic variant of the font. */
    ITALIC
}
